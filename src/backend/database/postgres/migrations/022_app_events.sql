-- Application activity events (ADR 0014, run backend-ops). Expand-only: one new table, one function, one trigger.
-- Append-only record of what the API did: request outcomes, rate-limit hits, sign-ins, provider-call outcome, latency and
-- cost. Queryable metadata sits in plain columns (route template, method, status, duration, provider, code); everything
-- else sits in `payload_enc`, a sealed envelope (enc1 or the padded enc2, AES-256-GCM, AAD app_events.payload_enc.<id>) the CHECK below forces.
-- No raw e-mail, token, document text, query text or IP address is ever stored: the client column is a keyed hash.
-- household_id, adult_user_id and case_id carry no foreign key on purpose: telemetry must never fail or be lost because a
-- referenced row is missing, and erasure is by explicit delete (AppEventRepository.eraseForHousehold / eraseForAdult).
-- Update is allowed only to redact the payload (consent revocation); delete is allowed (retention, erasure).
-- Row level security on with no policy; Data API roles hold nothing (see 016_data_api_lockdown.sql).
CREATE TABLE IF NOT EXISTS public.app_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  event_name text NOT NULL CHECK (event_name IN (
    'http_request', 'rate_limit_hit', 'provider_call', 'server_error', 'worker_event', 'consent_view', 'upload_attempt', 'readback_query', 'sign_in'
  )),
  request_id text CHECK (request_id IS NULL OR length(request_id) <= 64),
  household_id text CHECK (household_id IS NULL OR length(household_id) <= 100),
  adult_user_id text CHECK (adult_user_id IS NULL OR length(adult_user_id) <= 100),
  case_id text CHECK (case_id IS NULL OR length(case_id) <= 100),
  consent_grant_id text CHECK (consent_grant_id IS NULL OR length(consent_grant_id) <= 100),
  route text CHECK (route IS NULL OR length(route) <= 120),
  method text CHECK (method IS NULL OR method IN ('GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS')),
  status smallint CHECK (status IS NULL OR status BETWEEN 100 AND 599),
  duration_ms integer CHECK (duration_ms IS NULL OR duration_ms >= 0),
  provider text CHECK (provider IS NULL OR provider ~ '^[a-z0-9_.-]{1,64}$'),
  outcome text CHECK (outcome IS NULL OR outcome ~ '^[a-z0-9_.-]{1,64}$'),
  code text CHECK (code IS NULL OR code ~ '^[A-Za-z0-9_.-]{1,64}$'),
  client_hash text CHECK (client_hash IS NULL OR client_hash ~ '^[0-9a-f]{16}$'),
  payload_enc text CHECK (payload_enc IS NULL OR (payload_enc ~ '^enc[12][.]' AND length(payload_enc) <= 4096)),
  redacted_at timestamptz,
  CHECK (expires_at > occurred_at)
);

CREATE INDEX IF NOT EXISTS app_events_time_idx ON public.app_events (occurred_at);
CREATE INDEX IF NOT EXISTS app_events_name_time_idx ON public.app_events (event_name, occurred_at);
CREATE INDEX IF NOT EXISTS app_events_household_idx ON public.app_events (household_id, occurred_at) WHERE household_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS app_events_adult_idx ON public.app_events (adult_user_id) WHERE adult_user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS app_events_grant_idx ON public.app_events (consent_grant_id) WHERE consent_grant_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS app_events_expiry_idx ON public.app_events (expires_at);

CREATE OR REPLACE FUNCTION public.app_events_guard_update_fn() RETURNS trigger LANGUAGE plpgsql
SET search_path TO pg_catalog, public, pg_temp AS $$
BEGIN
  IF NEW.payload_enc IS NOT NULL OR NEW.redacted_at IS NULL
     OR (to_jsonb(NEW) - 'payload_enc' - 'redacted_at') IS DISTINCT FROM (to_jsonb(OLD) - 'payload_enc' - 'redacted_at') THEN
    RAISE EXCEPTION 'app events are append only';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS app_events_guard_update ON public.app_events;
CREATE TRIGGER app_events_guard_update
BEFORE UPDATE ON public.app_events
FOR EACH ROW EXECUTE FUNCTION public.app_events_guard_update_fn();

ALTER TABLE public.app_events ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
  api_role text;
BEGIN
  FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
      EXECUTE format('REVOKE ALL ON TABLE public.app_events FROM %I', api_role);
    END IF;
  END LOOP;
END
$$;
